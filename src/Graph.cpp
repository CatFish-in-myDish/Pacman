void Graph::initialiseGrid() {
  // 1. Create nodes for PATHS only
  for (int x = 0; x < WIDTH; x++) {
    for (int y = 0; y < HEIGHT; y++) {
      if (MAP[y][x] == 1) { // y is row, x is col
        Location loc(x, y);
        nodes[loc] = new Node(loc);
      }
    }
  }

  // 2. Connect neighbours
  for (auto &pair : nodes) {
    Node *current = pair.second;
    int x = current->getLocation().x;
    int y = current->getLocation().y;

    // Normal neighbours
    addNeighbour(current, x, y - 1);
    addNeighbour(current, x, y + 1);
    addNeighbour(current, x - 1, y);
    addNeighbour(current, x + 1, y);
  }

  // 3. Connect Tunnels / Toroidal wrapping
  // Automatically connect nodes on opposite edges (left-right, top-bottom)

  // Horizontal wrapping (Left <-> Right)
  for (int y = 0; y < HEIGHT; y++) {
    Node *left = getNode(0, y);
    Node *right = getNode(WIDTH - 1, y);
    if (left && right) {
      left->addNeighbour(right);
      right->addNeighbour(left);
    }
  }

  // Vertical wrapping (Top <-> Bottom)
  for (int x = 0; x < WIDTH; x++) {
    Node *top = getNode(x, 0);
    Node *bottom = getNode(x, HEIGHT - 1);
    if (top && bottom) {
      top->addNeighbour(bottom);
      bottom->addNeighbour(top);
    }
  }
}

void Graph::addNeighbour(Node *current, int nx, int ny) {
  // Only connect if neighbour exists (is a Path)
  // Tunnels are handled separately or via explicit wrapping if desired.
  // Here we strictly look for existing nodes.
  Node *neighbour = getNode(nx, ny);
  if (neighbour) {
    current->addNeighbour(neighbour);
  }
}

bool Graph::isWall(int x, int y) {
  if (x < 0 || x >= WIDTH || y < 0 || y >= HEIGHT)
    return true;
  return MAP[y][x] == 0;
}

Node *Graph::getNode(const Location &loc) {
  auto it = nodes.find(loc);
  if (it != nodes.end()) {
    return it->second;
  }
  return nullptr;
}

Node *Graph::getNode(int x, int y) { return getNode(Location(x, y)); }
